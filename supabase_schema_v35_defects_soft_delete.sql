-- 작성일: 2026-07-19
-- 실행 전 v34까지 적용되어 있어야 합니다.
--
-- 배경:
--   v34에서 하자 삭제를 직원까지 허용했는데, 직원이 실수로 삭제하면
--   지금까지는 실제 DELETE라 복구가 불가능했음 (사용 부속·상태이력·
--   코멘트까지 cascade로 완전히 사라짐).
--
--   → 삭제 버튼을 눌러도 실제로 행을 지우지 않고 deleted_at 시각만
--     기록하는 방식(소프트 삭제)으로 변경. 연결된 부속·이력·코멘트는
--     그대로 보존되므로 복구 시 전부 되살아남.
--   → 관리자 탭에 "휴지통"을 신설해 삭제된 하자를 복구하거나,
--     더는 필요 없으면 관리자가 영구삭제할 수 있게 함.
--
-- ★ 이 SQL과 함께 새 index.html 배포가 필요합니다.
--   (구버전 index.html은 삭제된 하자를 걸러내지 않고 그대로 보여줍니다)
-- ============================================================

-- ============================================================
-- 1) 소프트 삭제용 컬럼
-- ============================================================
alter table defects add column if not exists deleted_at timestamptz;
alter table defects add column if not exists deleted_by text;

comment on column defects.deleted_at is '소프트 삭제 시각 (null이면 정상 데이터, 값이 있으면 휴지통)';
comment on column defects.deleted_by is '삭제 실행자 표시 이름/이메일';


-- ============================================================
-- 2) 조회 정책 — 삭제된 하자는 admin만 볼 수 있음
--    (일반 목록 쿼리는 이제 index.html에서 deleted_at is null 조건을
--     추가로 걸어서 admin 화면에서도 평소엔 안 보이게 하고,
--     휴지통 화면에서만 조회. 이 RLS는 그 앞단의 최종 방어선)
-- ============================================================
drop policy if exists "sel_defects" on defects;
create policy "sel_defects" on defects
  for select using (
    auth.uid() is not null
    and (deleted_at is null or get_my_role() = 'admin')
  );


-- ============================================================
-- 3) 진짜 DELETE(영구삭제)는 다시 admin 전용으로
--    (일반 "삭제"는 이제 UPDATE(deleted_at 기록)로 처리되어 staff도
--     그대로 가능함 — upd_defects 정책(can_edit())을 따름.
--     여기서 막는 건 "복구 불가능한 완전 삭제"만 admin으로 한정하는 것)
-- ============================================================
drop policy if exists "del_defects" on defects;
create policy "del_defects" on defects for delete using (get_my_role() = 'admin');


